import {test, expect} from '@playwright/test';
import recorded from './fixtures/osrm-masinag.json';

test('route cards open details, preserve results on Back, save and start the chosen route', async ({page}) => {
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({contentType: 'image/png', path: 'e2e/fixtures/tile.png'}));
  await page.route('https://router.project-osrm.org/**', route => route.fulfill({json: recorded}));
  await page.goto('/');
  await page.getByRole('button', {name: 'Where to? Search routes'}).click();
  await page.getByRole('button', {name: 'Public transport demo', exact: true}).click();
  await page.getByRole('button', {name: 'Choose SM City Masinag - Cogeo Gate 2', exact: true}).click();
  await page.getByRole('button', {name: 'Road driving routes'}).click();
  await page.getByRole('button', {name: 'Find Routes', exact: true}).click();
  await page.getByRole('button', {name: 'Select Driving route 1', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Route Details', exact: true})).toBeVisible();
  await page.screenshot({path: 'test-results/route-details-412.png', fullPage: true});
  await expect(page.getByText('Fare unavailable', {exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'View route map', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Route Map', exact: true})).toBeVisible();
  const mapSurface = page.getByTestId('route-map-viewer').locator('.leaflet-container');
  await expect(mapSurface).toHaveCount(1);
  await expect(mapSurface.locator('.leaflet-overlay-pane path.leaflet-interactive')).toHaveCount(1);
  const bounds = await mapSurface.boundingBox();
  expect(bounds!.height).toBeGreaterThan(500);
  await page.mouse.move(bounds!.x + 100, bounds!.y + 150);
  await page.mouse.down();
  await page.mouse.move(bounds!.x + 180, bounds!.y + 230, {steps: 8});
  await page.mouse.up();
  await page.getByRole('button', {name: 'Show entire route', exact: true}).click();
  await page.getByRole('button', {name: 'Back to route details', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Route Details', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'How to get there?', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Navigate with Google Maps', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Save selected journey', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Journey saved on this device.');
  await page.getByRole('button', {name: 'Back to route results', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Route results', exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Select Driving route 1', exact: true})).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', {name: 'Select Driving route 1', exact: true}).click();
  await page.getByRole('button', {name: 'Start Route', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Your Route', exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Where to? Search routes'})).not.toBeVisible();
  await page.getByRole('button', {name: 'Finish route', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Where to? Search routes'})).toBeVisible();
  await expect(page.locator('.leaflet-overlay-pane path.leaflet-interactive')).toHaveCount(0);
});

